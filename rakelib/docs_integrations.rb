require_relative "../lib/messengerr"

# Renders docs/integrations.md from the integration registry so the reference cannot drift from the code.
# Lives outside docs.rake so specs can require it without loading Rake.
module DocsIntegrations
  PATH = File.expand_path("../docs/integrations.md", __dir__)

  FLAGS = { from: "--from", batch_size: "--batch-size", rate_limit: "--rate-limit" }.freeze

  # Every sending option needs a description here; render fails loudly if a new one is added without one.
  DESCRIPTIONS = {
    from: "Sender address or ID. Overrides the `from` stored with the credentials.",
    batch_size: "Messages per batch. Default 50.",
    rate_limit: "Batches per second. Default 10. Counts batches, not messages.",
    metadata: "Reserved. Not used by any built-in integration.",
    subject: "Fallback email subject when a message has none. The wizard supplies a rendered subject per message.",
    message_stream: "Postmark message stream (for example `outbound`).",
    tag: "Postmark tag for grouping messages in reports.",
    track_opens: "Postmark open tracking (`true` or `false`).",
    schedule: "ClickSend send time, as a Unix timestamp."
  }.freeze

  def self.integrations
    Messengerr::Registry.all.sort_by { |i| [ i.delivery_method.to_s, i.integration_key.to_s ] }
  end

  def self.render
    out = +<<~MD
      ---
      title: Integrations
      nav_order: 9
      description: "Reference for every messengerr integration: delivery method, credential keys, and sending options, generated from the code."
      ---

      # Integrations
      {: .no_toc }

      <!-- Generated by `bundle exec rake docs:integrations`. Do not edit by hand. -->

      An integration is the provider that delivers your messages. Set one up with `messengerr credentials setup NAME`. This page is generated from the code, so it always matches the installed version.

      | Integration | Delivers | Required credentials | Optional credentials |
      | --- | --- | --- | --- |
    MD
    integrations.each do |i|
      out << "| [`#{i.integration_key}`](##{i.integration_key}) | #{i.delivery_method} | #{keys(i.setup_class.required_keys)} | #{keys(i.setup_class.optional_keys)} |\n"
    end
    out << "\n"
    integrations.each { |i| out << detail(i) }
    out << footer
    out
  end

  def self.keys(list) = list.empty? ? "none" : list.map { |k| "`#{k}`" }.join(", ")

  def self.detail(integration)
    options = integration.options_class
    <<~MD
      ## `#{integration.integration_key}`
      {: .no_toc }

      - **Delivers:** #{integration.delivery_method}
      - **Set up with:** `messengerr credentials setup #{integration.integration_key}`
      - **Required credentials:** #{keys(integration.setup_class.required_keys)}
      - **Optional credentials:** #{keys(integration.setup_class.optional_keys)}
      - **Message formats:** #{integration.formats.join(', ')}#{limits(options)}

      | Sending option | Command-line flag | What it does |
      | --- | --- | --- |
      #{options.options.map { |name| option_row(name) }.join("\n")}

    MD
  end

  def self.limits(options)
    return "" unless options.const_defined?(:MAX_BATCH)

    "\n- **Maximum batch size:** #{options.const_get(:MAX_BATCH)}"
  end

  def self.option_row(name)
    description = DESCRIPTIONS.fetch(name) { raise "docs: add a DESCRIPTIONS entry for sending option :#{name} in rakelib/docs_integrations.rb" }
    flag = Messengerr::CLI::SendCommand::CLI_OPTIONS.include?(name) ? "`#{FLAGS.fetch(name)}`" : "not exposed yet"
    "| `#{name}` | #{flag} | #{description} |"
  end

  def self.footer
    <<~MD
      Options marked "not exposed yet" are supported by the integration but cannot be set from the command line today.

      How failures are classified as definite or uncertain for each provider is described in [Ledger and resume]({{ '/ledger-and-resume.html' | relative_url }}). To add your own, see [Writing an integration]({{ '/writing-an-integration.html' | relative_url }}).
    MD
  end
end
